#pragma once
#include <cstdint>

#include "move.h"

/// Тип оценки в записи: точная или граница, полученная при отсечении.
enum class TTFlag : uint8_t {
    Exact,       // оценка точная (в пределах окна alpha-beta)
    LowerBound,  // реальная оценка не меньше сохранённой (отсечение по beta)
    UpperBound,  // реальная оценка не больше сохранённой (ни один ход не поднял alpha)
};

/// Запись таблицы транспозиций, распакованная для использования в поиске.
struct TTEntry {
    uint64_t hash;
    int8_t depth;
    int16_t score;  // для мата хранится со смещением, см. `encode_mate_score`
    Move best_move;
    TTFlag flag;
    uint8_t age = 0;  // номер поиска, в котором запись сделана (см. `tt_new_search`)
};

static_assert(sizeof(TTEntry) == 16);

/// Задаёт размер таблицы: округляется вниз до степени двойки по числу записей.
/// Старое содержимое теряется. Не вызывать во время поиска.
void resize_transposition_table(int size_mb);

/// Ищет в таблице позицию с хешем `hash`. При успехе записывает данные в `out` и возвращает `true`.
/// Предусловие: таблица создана через `resize_transposition_table`.
bool tt_probe(uint64_t hash, TTEntry& out);

/// Сохраняет результат поиска. Существующая запись заменяется, если нвоая глубина не меньше или
/// запись сделана в предыдущем поиске. `depth` равна 0 для записей из `quiescence`. `score` для
/// мата должна быть уже преобразована через `encode_mate_score`.
void tt_store(uint64_t hash, int depth, int score, Move best_move, TTFlag flag);

/// Заранее подгружает слот для `hash` в кэш процессора, чтобы скрыть задержку памяти. Вызывается до
/// рекурсивного вызова поиска, который затем обратится к этой записи.
void tt_prefetch(uint64_t hash);

/// Преобразует оценку мата из "расстояние от корня" в "расстояние от текущего узла" перед записью в
/// таблицу. Так оценка не зависит от того, на какой глубине позиция встретилась. Остальные оценки
/// возвращаются без изменений.
int encode_mate_score(int score, int ply);

/// Обратное преобразование для оценки, прочитанной из таблицы, на глубине `ply`.
int decode_mate_score(int score, int ply);

/// Обнуляет все записи таблицы.
void clear_transposition_table();

/// Начинает новый поиск: увеличивает счётчик поколений, чтобы записи прошлых поисков вытеснялись
/// первыми.
void tt_new_search();
